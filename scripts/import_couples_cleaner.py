def split_embedded_narration(body: str) -> str:
    """Split "dialogue。Name...，"more-dialogue into paired quotes."""
    return re.sub(
        r'"([^"\n]+?[。！？])((?:林玉莹|叶晨|宋延)[^"\n]+?)，"',
        r'"\1"\2，"',
        body,
    )


def close_dialogue_quotes(body: str) -> str:
    """Add missing closing quotes on dialogue-only paragraphs."""
    lines = body.split('\n')
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if not stripped:
            out.append(line)
            continue
        if stripped.startswith('【') and stripped.endswith('】'):
            out.append(line)
            continue
        if stripped.count('"') % 2 == 1:
            line = line.rstrip() + '"'
        out.append(line)
    return '\n'.join(out)


