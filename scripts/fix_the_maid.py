def strip_line_noise(line: str) -> str:
    line = WATERMARK.sub('', line)
    return line.strip()


def drop_orphanage_paragraph(body: str) -> str:
    chunks = re.split(r'\n\s*\n', body)
    kept = [chunk for chunk in chunks if ORPHANAGE_PARA not in chunk]
    return '\n\n'.join(kept)


def extract_opening(raw_body: str) -> str:
    end = raw_body.find('以后我慢慢告诉你。')
    if end < 0:
        raise ValueError('opening end marker not found')
    end += len('以后我慢慢告诉你。')
    if end < len(raw_body) and raw_body[end] in '"”':
        end += 1
    opening = raw_body[:end]
    opening = opening.replace('# 一', '').strip()
    return opening


def extract_from_chapter_two(raw_body: str) -> str:
    idx = raw_body.find('\n林洁如2')
    if idx < 0:
        raise ValueError('林洁如2 not found')
    return raw_body[idx:].lstrip()


def retitle_chapters(body: str) -> str:
    for old, title in zip(CHAPTER_MARKERS, CHAPTER_TITLES):
        body = re.sub(
            rf'(?m)^[ \t]*{re.escape(old)}[ \t]*$',
            f'# {title}',
            body,
        )
    return body


def collapse_cjk_wrap(body: str) -> str:
    previous = None
    while previous != body:
        previous = body
        body = CJK_SPACE.sub(r'\1\2', body)
    return body


def normalize_paragraphs(body: str) -> str:
    chunks = re.split(r'\n\s*\n', body)
    cleaned: list[str] = []
    for chunk in chunks:
        lines = [strip_line_noise(line) for line in chunk.splitlines()]
        lines = [line for line in lines if line]
        if not lines:
            continue
        if any(AUTHOR_ASIDE.match(line) for line in lines):
            continue
        text = ''.join(lines) if len(lines) > 1 and not lines[0].startswith('#') else '\n'.join(lines)
        if lines[0].startswith('#'):
            text = '\n'.join(lines)
        else:
            text = ''.join(lines)
        text = text.strip()
        if text:
            cleaned.append(text)
    return '\n\n'.join(cleaned)


