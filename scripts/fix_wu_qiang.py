def preprocess(body: str) -> str:
    """Strip leftover heading marker and OCR paragraph glue."""
    body = re.sub(r'^# 吴强\n+', '# 吴强\n\n', body)
    body = body.replace('\u201c', '"').replace('\u201d', '"')
    body = re.sub(r"。\('", '。\n\n', body)
    body = re.sub(r"^\('", '', body, flags=re.M)
    body = body.replace("('", '')
    body = re.sub(r'[ \t]+\n', '\n', body)
    body = re.sub(r'\n{3,}', '\n\n', body)
    body = re.sub(r'^(# .+)\n(?!\n)', r'\1\n\n', body, flags=re.M)
    body = body.replace(
        '把两根手指熟练的塞入了张梅娇嫩的阴道里……\n张梅如同一颗',
        '把两根手指熟练的塞入了张梅娇嫩的阴道里……\n\n张梅如同一颗',
    )
    body = body.replace(
        '总会感到一阵阵的空虚。\n那年的冬天',
        '总会感到一阵阵的空虚。\n\n那年的冬天',
    )
    return body


