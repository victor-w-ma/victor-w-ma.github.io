def strip_fullwidth_indent(body: str) -> str:
    """Published posts do not use fullwidth paragraph indent."""
    return re.sub(r'^　　', '', body, flags=re.M)


def normalize_cn_ellipsis(body: str) -> str:
    """Turn Chinese run-on dots/commas into ……."""
    body = re.sub(r'。{2,}', '……', body)
    body = re.sub(r'，{2,}', '……', body)
    body = re.sub(r'(?:。，|，。){1,}[。，]*', '……', body)
    return body


def normalize_halfwidth_punct(body: str) -> str:
    """Convert leftover halfwidth sentence punctuation."""
    body = body.replace('?', '？').replace('!', '！')
    body = re.sub(r'([\u4e00-\u9fff]):', r'\1：', body)
    return body


def capitalize_role_tags(body: str) -> str:
    """Uppercase leftover S/M/SM/QQ/PDD/JK/SP role and product tags."""
    body = re.sub(r'(?<![A-Za-z])sm(?![A-Za-z])', 'SM', body)
    body = re.sub(r'(?<![A-Za-z])qq(?![A-Za-z])', 'QQ', body, flags=re.I)
    body = re.sub(r'(?<![A-Za-z])pdd(?![A-Za-z])', 'PDD', body, flags=re.I)
    body = re.sub(r'(?<![A-Za-z])jk(?![A-Za-z])', 'JK', body, flags=re.I)
    body = re.sub(r'(?<![A-Za-z])sp(?![A-Za-z])', 'SP', body)
    body = re.sub(r'(?<![A-Za-z])yy(?![A-Za-z])', '意淫', body)
    body = re.sub(r'(?<![A-Za-z])low(?![A-Za-z])', '低俗', body)
    body = re.sub(r'([\u4e00-\u9fff])s(?![A-Za-z])', r'\1S', body)
    body = re.sub(r'([\u4e00-\u9fff])m(?![A-Za-z])', r'\1M', body)
    return body


def repair_quotes(body: str) -> str:
    """Fix high-confidence inverted or missing quotation marks."""
    for old, new in QUOTE_REPLACEMENTS:
        body = body.replace(old, new)
    # Speech verb + comma + closer-as-opener.
    body = re.sub(
        r'((?:说|问|讲|喊|骂|道|回|答)(?:道)?)，”(?=[\u4e00-\u9fff])',
        r'\1，“',
        body,
    )
    body = re.sub(
        r'((?:说|问|讲|喊|骂|道|回|答)(?:道)?)：”(?=[\u4e00-\u9fff])',
        r'\1：“',
        body,
    )
    missing_openers = (
        '好看么？欣赏着',
        '虽然你的到来给原本平静',
        '贱畜，不会动的么',
        '把你的双手还有你沾满屎',
        '昨晚好像我有些放纵了',
    )
    lines = []
    for line in body.splitlines():
        if line.startswith('”'):
            line = '“' + line[1:]
        for opener in missing_openers:
            if line.startswith(opener):
                line = '“' + line
                break
        lines.append(line)
    return '\n'.join(lines)


def ensure_header_spacing(body: str) -> str:
    """Blank line before and after markdown headings."""
    body = re.sub(r'(?<!\n)\n(#{1,2} )', r'\n\n\1', body)
    body = re.sub(r'(#{1,2} .+)\n(?!\n|#)', r'\1\n\n', body)
    body = re.sub(r'\n{3,}', '\n\n', body)
    return body


